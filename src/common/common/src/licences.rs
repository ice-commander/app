//! What the application is made of and under what terms, carried in the binary.
//!
//! Built in rather than installed beside the application: every platform packaged them
//! differently and Android not at all, so the one place a user could always reach them was
//! nowhere. Here they are the same text in every build and every frontend.

/// A licence or a list the application can show.
pub struct Document {
    /// What to call it on screen.
    pub title: &'static str,
    pub text: &'static str,
}

/// Ice Commander's own terms.
pub const OURS: &[Document] = &[
    Document {
        title: "MIT",
        text: include_str!("../../../../assets/licenses/LICENSE-MIT.txt"),
    },
    Document {
        title: "Apache 2.0",
        text: include_str!("../../../../assets/licenses/LICENSE-APACHE-2.0.txt"),
    },
];

/// The libraries shipped alongside it, and where their source can be had.
pub const BUNDLED: Document = Document {
    title: "Bundled components",
    text: include_str!("../../../../assets/licenses/BUNDLED-COMPONENTS.txt"),
};

/// Everything the Rust side depends on, generated by `npm run licenses`.
pub const DEPENDENCIES: Document = Document {
    title: "Rust dependencies",
    text: include_str!("../../../../THIRD-PARTY-LICENSES.md"),
};

/// The terms those libraries are under.
pub const OTHERS: &[Document] = &[
    Document {
        title: "LGPL 2.1",
        text: include_str!("../../../../assets/licenses/LGPL-2.1.txt"),
    },
    Document {
        title: "LGPL 3.0",
        text: include_str!("../../../../assets/licenses/LGPL-3.0.txt"),
    },
    Document {
        title: "GPL 3.0",
        text: include_str!("../../../../assets/licenses/GPL-3.0.txt"),
    },
    Document {
        title: "GCC Runtime Library Exception",
        text: include_str!("../../../../assets/licenses/GCC-exception-3.1.txt"),
    },
    Document {
        title: "FreeType (FTL)",
        text: include_str!("../../../../assets/licenses/FreeType-FTL.txt"),
    },
];

/// Everything, in the order it is worth reading.
pub fn all() -> Vec<&'static Document> {
    let mut held: Vec<&'static Document> = vec![&BUNDLED, &DEPENDENCIES];
    held.extend(OURS.iter());
    held.extend(OTHERS.iter());
    held
}

#[cfg(test)]
mod tests {
    use super::*;

    /// They are built in, so an empty one means a file went missing from the build rather than
    /// from the installer — and nobody would notice until a user opened the page.
    #[test]
    fn every_document_says_something() {
        for document in all() {
            assert!(
                document.text.len() > 100,
                "{} is empty or truncated",
                document.title
            );
            assert!(!document.title.is_empty());
        }
    }

    #[test]
    fn the_bundled_list_names_the_libraries_it_ships() {
        assert!(BUNDLED.text.contains("GTK"), "the GTK stack is listed");
        assert!(
            BUNDLED.text.contains("LGPL"),
            "and the terms it is under: that is why the list exists"
        );
    }

    #[test]
    fn our_own_terms_are_both_there() {
        let titles: Vec<&str> = OURS.iter().map(|d| d.title).collect();
        assert_eq!(titles, ["MIT", "Apache 2.0"]);
    }
}
